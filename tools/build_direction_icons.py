def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (glyph, top, bottom) in ICONS.items():
        (OUT / f'{name}.svg').write_text(TEMPLATE.format(glyph=GLYPHS[glyph], top=top, bottom=bottom), encoding='utf-8')
    print(f'{len(ICONS)} icons written to {OUT}')


if __name__ == '__main__':
    main()
